#!/usr/bin/env bash
# FashionMNIST death_activity_fraction ablation: N0=20, 4 fractions x 5 seeds.
# Usage: bash src_self_organization/run_activity_fraction.sh [start|stop]
set -Eeuo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_DIR"

FRACTIONS=(0.05 0.10 0.20 0.40)
SEEDS=(0 1 2 3 4)
N0=20
DATASET="${DATASET:-fashionmnist}"
OUTPUT_ROOT="${OUTPUT_ROOT:-data/neurogenesis/activity_fraction_ablations}"
RUN_DIR="$OUTPUT_ROOT/.run_control"
LOG_DIR="$OUTPUT_ROOT/logs"
PID_FILE="$RUN_DIR/main.pid"
CHILD_FILE="$RUN_DIR/children.pid"
# Temporary trainer is generated by this shell script; original trainer is untouched.
TEMP_MODULE="src_self_organization/_train_activity_fraction_ablation.py"

stop_all() {
  if [[ -f "$CHILD_FILE" ]]; then
    while IFS= read -r pid; do
      [[ -n "$pid" ]] || continue
      pkill -TERM -P "$pid" 2>/dev/null || true
      kill -TERM "$pid" 2>/dev/null || true
    done < "$CHILD_FILE"
  fi
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    [[ "$pid" == "$$" ]] || kill -TERM "$pid" 2>/dev/null || true
  fi
}
case "${1:-start}" in
  stop) stop_all; echo 'Stop requested.'; exit 0 ;;
  start) ;;
  *) echo "Usage: bash $0 [start|stop]" >&2; exit 2 ;;
esac

mkdir -p "$RUN_DIR" "$LOG_DIR"
if [[ -f "$PID_FILE" ]]; then
  old_pid="$(cat "$PID_FILE")"
  if kill -0 "$old_pid" 2>/dev/null; then
    echo "Already running with PID $old_pid; use bash $0 stop" >&2
    exit 1
  fi
fi

# Prepare an isolated copy of the trainer with the correct parameter changed.
# The provided trainer's --ablation death varies death_flux_max, NOT death_activity_fraction.
python - "$TEMP_MODULE" <<'PY'
from pathlib import Path
import sys
source = Path('src_self_organization/train_neurogenesis_ablation.py')
target = Path(sys.argv[1])
code = source.read_text()
old = 'cfg.death_flux_max = float(args.value)'
assert code.count(old) == 1, 'Expected exactly one death_flux_max assignment in trainer'
code = code.replace(old, 'cfg.death_activity_fraction = float(args.value)')
# Store results under an accurately named ablation subdirectory.
old_dir = 'save_dir = (output_root / cfg.dataset.lower() / args.ablation'
assert code.count(old_dir) == 1, 'Unexpected trainer save_dir layout'
code = code.replace(old_dir, 'save_dir = (output_root / cfg.dataset.lower() / "activity_fraction"')
target.write_text(code)
print(f'Created temporary trainer: {target} (original unchanged)')
PY

printf '%s\n' "$$" > "$PID_FILE"
: > "$CHILD_FILE"
children=()
cleanup() {
  trap - EXIT INT TERM
  for pid in "${children[@]}"; do
    pkill -TERM -P "$pid" 2>/dev/null || true
    kill -TERM "$pid" 2>/dev/null || true
  done
  rm -f "$PID_FILE" "$CHILD_FILE" "$TEMP_MODULE"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

printf 'Dataset=%s | N0=%d | birth_threshold=0.25 | death_activity_fraction=%s | seeds=%s | runs=20\n' \
  "$DATASET" "$N0" "${FRACTIONS[*]}" "${SEEDS[*]}"
for fraction in "${FRACTIONS[@]}"; do
  echo "=== death_activity_fraction=$fraction: launching five seeds ==="
  children=()
  : > "$CHILD_FILE"
  for seed in "${SEEDS[@]}"; do
    log="$LOG_DIR/activity_fraction_${fraction}_N${N0}_seed${seed}.log"
    (
      set -o pipefail
      python -u -m src_self_organization._train_activity_fraction_ablation \
        --dataset "$DATASET" \
        --hidden_neurons "$N0" \
        --seed "$seed" \
        --ablation death \
        --value "$fraction" \
        --output_dir "$OUTPUT_ROOT" \
        2>&1 | tee "$log" | sed -u "s/^/[activity_fraction=$fraction N0=$N0 seed=$seed] /"
    ) &
    pid=$!
    children+=("$pid")
    echo "$pid" >> "$CHILD_FILE"
  done
  failed=0
  for pid in "${children[@]}"; do
    wait "$pid" || failed=1
  done
  children=()
  : > "$CHILD_FILE"
  if (( failed )); then
    echo "ERROR: at least one experiment failed for fraction=$fraction; check $LOG_DIR" >&2
    exit 1
  fi
  echo "=== Completed fraction=$fraction ==="
done
echo 'All 20 death-activity-fraction experiments completed.'